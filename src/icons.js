/**
 * Get the SVG icon for an activity title.
 */
export function activityIcon(title) {
  switch (title) {
    case 'Обед': return mealIcon();
    case 'Сон': return sleepIcon();
    case 'Занятие': return paletteIcon();
    case 'Прогулка': return walkIcon();
    default: return clipboardIcon(22);
  }
}

/**
 * Get the CSS class for an activity icon background.
 */
export function activityClass(title) {
  switch (title) {
    case 'Обед': return 'meal';
    case 'Сон': return 'sleep';
    case 'Занятие': return 'activity';
    case 'Прогулка': return 'walk';
    default: return 'other';
  }
}

/**
 * Generate an avatar initial from a child's name.
 * Returns the initial letter and a hue for CSS styling.
 */
export function avatarInitials(firstName, lastName = '') {
  const initials = (firstName[0] || '') + (lastName[0] || '');
  const hue = (firstName.charCodeAt(0) * 37) % 360;
  return { initials: initials.toUpperCase(), hue };
}

